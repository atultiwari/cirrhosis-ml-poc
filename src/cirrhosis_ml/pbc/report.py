"""Markdown report for Track A Phase 2 (``reports/pbc_report.md``). Aggregate results only."""

from __future__ import annotations

from pathlib import Path

import pandas as pd

from cirrhosis_ml.pbc.phase2 import Phase2Config, Phase2Results

DISC_METRICS = {"harrell_c": "Harrell C", "uno_c_tau10": "Uno C (τ=10 y)",
                "td_auc_2": "AUC 2 y", "td_auc_5": "AUC 5 y", "td_auc_10": "AUC 10 y"}


def _ci(row: pd.Series) -> str:
    return f"{row['estimate']:.3f} ({row['ci_lower']:.3f}–{row['ci_upper']:.3f})"


def discrimination_table(res: Phase2Results) -> pd.DataFrame:
    disc = res.discrimination.reset_index()
    disc = disc[disc["metric"].isin(DISC_METRICS)]
    table = disc.assign(value=disc.apply(_ci, axis=1)).pivot(index="model", columns="metric",
                                                            values="value")
    table = table.loc[list(res.labels), list(DISC_METRICS)].rename(columns=DISC_METRICS)
    fold = res.fold_summary
    table["Harrell C, per repeat mean (range)"] = [_range(res.per_repeat, m, "harrell_c")
                                                   for m in table.index]
    table["IBS (yearly 1–7 y), fold mean (SD)"] = [
        f"{fold.loc[m, 'ibs_mean']:.3f} ({fold.loc[m, 'ibs_sd']:.3f})" for m in table.index]
    table["Harrell C, fold mean (SD)"] = [
        f"{fold.loc[m, 'harrell_c_mean']:.3f} ({fold.loc[m, 'harrell_c_sd']:.3f})"
        for m in table.index]
    return table.rename(index=res.labels)


def _calibration(res: Phase2Results) -> pd.DataFrame:
    c = res.calibration
    return pd.DataFrame({
        "O/E (5 y)": c["O/E"].map("{:.2f}".format),
        "Calibration slope (95% CI)": [f"{r.slope:.2f} ({r.slope_lo:.2f}–{r.slope_hi:.2f})"
                                       for r in c.itertuples()],
        "O/E, per repeat mean (range)": [_range(res.per_repeat, m, "oe", 2) for m in c.index],
        "Slope, per repeat mean (range)": [_range(res.per_repeat, m, "slope", 2)
                                           for m in c.index],
    }).rename(index=res.labels)


def _range(per_repeat: pd.DataFrame, model: str, metric: str, digits: int = 3) -> str:
    r = per_repeat.loc[model, metric]
    return f"{r['mean']:.{digits}f} ({r['min']:.{digits}f}–{r['max']:.{digits}f})"


def differences_table(res: Phase2Results) -> pd.DataFrame:
    d = res.differences.reset_index()
    d = d[d["metric"].isin(DISC_METRICS)]
    table = d.assign(value=d.apply(_ci, axis=1)).pivot(index="model", columns="metric",
                                                      values="value")
    order = [m for m in res.labels if m in table.index]
    return table.loc[order, list(DISC_METRICS)].rename(columns=DISC_METRICS, index=res.labels)


def _competing(res: Phase2Results) -> pd.DataFrame:
    rows = []
    for model, g in res.competing.groupby("model", sort=False):
        top = g.iloc[-1]
        gap_km = (g.mean_predicted - g.observed_km).abs().mean()
        gap_aj = (g.mean_predicted - g.observed_aj).abs().mean()
        rows.append({
            "model": res.labels[model],
            "mean |pred − KM| over deciles": f"{gap_km:.3f}",
            "mean |pred − AJ| over deciles": f"{gap_aj:.3f}",
            "top decile: pred / KM / AJ": f"{top.mean_predicted:.2f} / {top.observed_km:.2f} / "
                                          f"{top.observed_aj:.2f}",
        })
    return pd.DataFrame(rows).set_index("model")


def _fig(res: Phase2Results, key: str, out_path: Path, caption: str) -> str:
    path = res.figures.get(key)
    if path is None:
        return ""
    return f"![{caption}]({path.relative_to(out_path.parent).as_posix()})\n"


def _md(df: pd.DataFrame, floatfmt: str = ".3f") -> str:
    return df.to_markdown(floatfmt=floatfmt)


def _md_text(df: pd.DataFrame) -> str:
    """Markdown table that keeps pre-formatted strings as they are."""
    return df.to_markdown(disable_numparse=True)


def write_report(res: Phase2Results, cfg: Phase2Config, out_path: Path) -> Path:
    sens = res.sensitivity.assign(model=res.sensitivity["model"].map(res.labels))
    sens = sens.round(3).astype(str)
    shap_figs = "\n".join(_fig(res, k, out_path, k) for k in sorted(res.figures)
                          if k.startswith("shap_"))
    text = f"""# Track A — Mayo PBC survival models: report

Generated by `uv run python -m cirrhosis_ml.pbc.run_all`. Open data (UCI 878, CC BY 4.0).
Phase 1 outputs (table 1, missingness, KM curves, apparent Mayo performance) are in `reports/pbc/`.

## Methods (summary)
- **Population:** 312 randomised trial patients (primary). **Outcome:** death; liver transplant
  censored. **Horizon:** {cfg.horizon:g} years for risk, calibration and decision curves.
- **Models:** published Mayo score (fixed); Cox on the 5 Mayo variables refitted in each fold;
  Cox, elastic-net Cox, random survival forest and gradient-boosted Cox on 16 candidate
  predictors (8 log-transformed labs). Imputation (chained equations) and scaling are fitted
  inside each training fold.
- **Validation:** repeated nested CV — outer 5-fold × {cfg.n_repeats} repeats (stratified on
  death), inner 3-fold grid search on the outer training fold only. Each patient's out-of-fold
  (OOF) {cfg.horizon:g}-year risk is averaged over repeats; discrimination CIs are
  {cfg.n_boot}-resample percentile bootstraps of these OOF predictions (they ignore refitting
  variability, so are somewhat narrow). Averaging over repeats acts like a small ensemble, so
  per-repeat results (each a single CV pass) are shown as mean (range) alongside; fold-level
  mean (SD) is also given.
- The published Mayo score was fitted on these same patients (Dickson 1989), so its performance
  is **optimistic**; the refitted Mayo-variable Cox is the fair benchmark.

## Sample size (Riley et al. criteria; Python implementation)
{_md(res.sample_size.set_index(["scenario", "parameters"]))}

## Discrimination (OOF, 95% bootstrap CI)
{_md(discrimination_table(res))}

## Paired difference vs the refitted Mayo-variable Cox (model − benchmark, 95% bootstrap CI)
A CI that excludes 0 indicates a difference on the same patients. These are descriptive,
unadjusted comparisons (5 models × 5 metrics); no multiplicity correction.

{_md_text(differences_table(res))}

## Calibration at {cfg.horizon:g} years (OOF)
Slope < 1: predictions too extreme (overfitting); > 1: too conservative. Averaging OOF risks over
repeats compresses their spread a little (raising the slope), so the mean of per-repeat slopes is
also shown.

{_md_text(_calibration(res))}

{_fig(res, "calibration", out_path, "Calibration")}
## Decision-curve analysis at {cfg.horizon:g} years (net benefit, OOF)
{_md(res.dca.rename(columns=res.labels))}

{_fig(res, "dca", out_path, "Decision curves")}
## Refitted Mayo-variable Cox vs Dickson 1989 (coefficients per original unit, n = 312)
{_md(res.mayo_coefficients)}

## Proportional-hazards checks (Schoenfeld, rank time; final models on all 312)
**Mayo-variable Cox**

{_md(res.ph_tests["mayo_refit"])}

**Cox, all 16 predictors** (lowest p-values)

{_md(res.ph_tests["cox_full"].head(6))}

## Explainability (final models refitted on all 312 — apparent, descriptive only)
Permutation importance = mean drop in Harrell's C when a predictor is shuffled (20 repeats),
computed on the training data: forests and boosting fit these data almost perfectly, so their
importances are inflated and not comparable in size with the Cox models — read the ranking only.

{_md(res.importance, ".4f")}

{shap_figs}
## Sensitivity analyses ({cfg.sens_repeats} repeats; point estimates on OOF risk, no CIs)
The published Mayo score was fitted on all 418 patients (death outcome), so its rows are
apparent performance; in the composite analysis it predicts death, not death-or-transplant.

{_md_text(sens.set_index(["analysis", "model"]))}

### Transplant as a competing event
Observed {cfg.horizon:g}-year death risk per decile of OOF predicted risk: Kaplan–Meier
(transplant censored) vs Aalen–Johansen cumulative incidence (transplant competing).

{_md(_competing(res))}

{_fig(res, "cif", out_path, "Cumulative incidence")}
## Limitations
- Small sample (312 patients, 125 deaths) from a single 1974–84 trial; see sample-size table.
- No external validation; OOF bootstrap CIs understate model-refitting uncertainty.
- Single deterministic chained-equations imputation per fold (not multiple imputation with
  Rubin's rules).
- Fine–Gray models not fitted (no mature Python implementation); competing risks are handled
  descriptively with Aalen–Johansen.
"""
    out_path.write_text(text, encoding="utf-8")
    return out_path
